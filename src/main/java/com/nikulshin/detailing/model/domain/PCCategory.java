package com.nikulshin.detailing.model.domain;

/**
 * Статья платёжного календаря.
 * Продажи товаров (розница/сопутствующие товары) сознательно не включены:
 * в поступлениях — только заказы по факту завершения и прочие поступления.
 */
public enum PCCategory {
    // Поступления
    CLIENT_ORDER,    // Заказы (автоматически, по факту завершения работ)
    OTHER_INCOME,    // Прочие поступления

    // Платежи
    RENT,            // Аренда
    UTILITIES,       // Коммунальные платежи
    SALARY,          // Зарплата (ФОТ)
    MATERIALS,       // Материалы и химия
    TAXES,           // Налоги
    ACQUIRING,       // Эквайринг / комиссии
    OTHER_EXPENSE    // Прочие расходы
}
